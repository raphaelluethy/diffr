#!/usr/bin/env python3
"""Generate src/data.rs and the icon SVGs from a Go file of string maps made from @pierre/trees.

Usage: python3 -I tools/gen.py <path/to/data.go> <crate dir> <svg out dir>
"""
import json
import os
import re
import sys

src, crate, svg_dir = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(src, encoding="utf-8").read()

maps = {}
for m in re.finditer(r"^var (\w+) = map\[string\]string\{\n(.*?)^\}", text, re.S | re.M):
    entries = []
    for line in m.group(2).splitlines():
        line = line.strip()
        if not line:
            continue
        km = re.match(r'("(?:[^"\\]|\\.)*")\s*:\s*("(?:[^"\\]|\\.)*"),$', line)
        if not km:
            sys.exit(f"cannot parse line in {m.group(1)}: {line[:80]}")
        entries.append((json.loads(km.group(1)), json.loads(km.group(2))))
    maps[m.group(1)] = sorted(entries)

need = ["symbols", "byName", "byExtension", "overrides", "lightColors", "darkColors"]
for n in need:
    if n not in maps:
        sys.exit(f"missing map {n}")

# Tokens the lookup tables name but no icon draws (the data has "zip")
# fall back to the default icon, so every returned token has an SVG.
icons = {t for t, _ in maps["symbols"]}
missing = set()
for n in ("byName", "byExtension", "overrides"):
    fixed = []
    for k, v in maps[n]:
        if v not in icons:
            missing.add(v)
            v = "default"
        fixed.append((k, v))
    maps[n] = fixed
if missing:
    print("no icon for", sorted(missing), "-> default", file=sys.stderr)

os.makedirs(svg_dir, exist_ok=True)
for token, svg in maps["symbols"]:
    with open(os.path.join(svg_dir, token + ".svg"), "w", encoding="utf-8") as f:
        f.write(svg if svg.endswith("\n") else svg + "\n")


def color(s):
    s = s.lstrip("#")
    if len(s) != 6:
        sys.exit(f"unexpected color #{s}")
    return "0x" + s.lower()


def rs_str(s):
    return json.dumps(s)


out = [
    "// Code generated by tools/gen.py from a Go file of its tables",
    "// (itself generated from @pierre/trees); DO NOT EDIT.",
    "// The icons are © 2025 Pierre Computer Company, under the Apache License 2.0",
    "// in LICENSE-icons.",
    "",
    "/// Every icon token, sorted.",
    "pub static TOKENS: &[&str] = &[",
]
out += [f"    {rs_str(t)}," for t, _ in maps["symbols"]]
out.append("];\n")


def table(name, doc, entries, conv):
    out.append(f"/// {doc} Sorted by key, for binary search.")
    out.append(f"pub(crate) static {name}: &[(&str, {'u32' if conv is color else '&str'})] = &[")
    for k, v in entries:
        out.append(f"    ({rs_str(k)}, {conv(v)}),")
    out.append("];\n")


table("BY_NAME", "Tokens of files by their whole name, in lower case.", maps["byName"], rs_str)
table("BY_EXTENSION", "Tokens of files by their extension, in lower case.", maps["byExtension"], rs_str)
table("OVERRIDES", "Extensions whose icons are more specific than the language's.", maps["overrides"], rs_str)
table("LIGHT_COLORS", "Icon colors in the light theme, 0xRRGGBB.", maps["lightColors"], color)
table("DARK_COLORS", "Icon colors in the dark theme, 0xRRGGBB.", maps["darkColors"], color)

with open(os.path.join(crate, "src", "data.rs"), "w", encoding="utf-8") as f:
    f.write("\n".join(out).rstrip() + "\n")
print(f"{len(maps['symbols'])} icons")
